#!/usr/bin/env python3
"""Validate tests/vectors/frames.json and generate frames_vectors.h from it.

frames.json is the single source of truth for wire-format test vectors. It is
shared by the C tests and the Python host implementation. This script checks
every vector against an independent Python encoder, then writes a C header.

Usage:
    python gen_vectors.py           regenerate frames_vectors.h
    python gen_vectors.py --check   fail if frames_vectors.h is out of date
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
JSON_PATH = HERE / "frames.json"
HEADER_PATH = HERE / "frames_vectors.h"


def crc8(data: bytes) -> int:
    crc = 0
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = ((crc << 1) ^ 0x07) & 0xFF if crc & 0x80 else (crc << 1) & 0xFF
    return crc


def crc16(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def encode(ftype: int, seq: int, payload: bytes) -> bytes:
    header = bytes([len(payload), ftype, seq])
    header += bytes([crc8(header)])
    crc = crc16(header + payload)
    return bytes([0x7E]) + header + payload + bytes([crc & 0xFF, crc >> 8])


def hexbytes(s: str) -> bytes:
    return bytes.fromhex(s.replace(" ", ""))


def c_array(data: bytes) -> str:
    if not data:
        return "{0}"
    return "{" + ", ".join(f"0x{b:02X}" for b in data) + "}"


def main() -> int:
    vectors = json.loads(JSON_PATH.read_text(encoding="utf-8"))

    check = vectors["crc_check"]
    data = check["input"].encode("ascii")
    assert crc8(data) == int(check["crc8"], 16), "crc8 check value mismatch"
    assert crc16(data) == int(check["crc16"], 16), "crc16 check value mismatch"

    lines = [
        "/* Generated by tests/vectors/gen_vectors.py from frames.json. Do not edit. */",
        "#ifndef FRAMES_VECTORS_H",
        "#define FRAMES_VECTORS_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f'#define FL_VEC_CRC_INPUT "{check["input"]}"',
        f"#define FL_VEC_CRC8_CHECK 0x{int(check['crc8'], 16):02X}u",
        f"#define FL_VEC_CRC16_CHECK 0x{int(check['crc16'], 16):04X}u",
        "",
        "typedef struct fl_vector {",
        "    const char *name;",
        "    uint8_t type;",
        "    uint8_t seq;",
        "    const uint8_t *payload;",
        "    size_t payload_len;",
        "    const uint8_t *encoded;",
        "    size_t encoded_len;",
        "} fl_vector;",
        "",
    ]

    entries = []
    for i, v in enumerate(vectors["frames"]):
        ftype = int(v["type"], 16)
        seq = int(v["seq"], 16)
        payload = hexbytes(v["payload"])
        encoded = hexbytes(v["encoded"])
        expected = encode(ftype, seq, payload)
        if encoded != expected:
            print(f"vector '{v['name']}' is wrong.\n  file:     {encoded.hex(' ')}\n"
                  f"  expected: {expected.hex(' ')}", file=sys.stderr)
            return 1
        lines.append(f"static const uint8_t fl_vec_payload_{i}[] = {c_array(payload)};")
        lines.append(f"static const uint8_t fl_vec_encoded_{i}[] = {c_array(encoded)};")
        entries.append(
            f'    {{"{v["name"]}", 0x{ftype:02X}u, 0x{seq:02X}u, fl_vec_payload_{i}, '
            f"{len(payload)}u, fl_vec_encoded_{i}, {len(encoded)}u}},"
        )

    lines += ["", "static const fl_vector fl_vectors[] = {", *entries, "};", "",
              "#define FL_VECTOR_COUNT (sizeof fl_vectors / sizeof fl_vectors[0])",
              "", "#endif /* FRAMES_VECTORS_H */", ""]
    generated = "\n".join(lines)

    if "--check" in sys.argv:
        current = HEADER_PATH.read_text(encoding="utf-8") if HEADER_PATH.exists() else ""
        if current != generated:
            print("frames_vectors.h is out of date. Run gen_vectors.py.", file=sys.stderr)
            return 1
        print(f"{len(entries)} vectors valid, header up to date.")
        return 0

    HEADER_PATH.write_text(generated, encoding="utf-8", newline="\n")
    print(f"{len(entries)} vectors valid, wrote {HEADER_PATH.name}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
